CREATE TABLE IF NOT EXISTS context_artifacts (
  artifact_id VARCHAR(36) NOT NULL,
  raw_ref VARCHAR(768) NOT NULL,
  storage_backend VARCHAR(32) NOT NULL DEFAULT 'local',
  bucket VARCHAR(255) NULL,
  object_key VARCHAR(1024) NULL,
  thread_id VARCHAR(128) NOT NULL,
  run_id VARCHAR(128) NULL,
  unit_id VARCHAR(128) NULL,
  source_tool VARCHAR(128) NOT NULL,
  size_chars BIGINT NOT NULL DEFAULT 0,
  sha256 VARCHAR(64) NOT NULL,
  suffix VARCHAR(32) NOT NULL DEFAULT '.txt',
  attributes JSON NULL,
  preview TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (artifact_id),
  UNIQUE KEY uq_context_artifacts_raw_ref (raw_ref),
  KEY ix_context_artifacts_storage_backend (storage_backend),
  KEY ix_context_artifacts_thread_id (thread_id),
  KEY ix_context_artifacts_run_id (run_id),
  KEY ix_context_artifacts_unit_id (unit_id),
  KEY ix_context_artifacts_source_tool (source_tool),
  KEY ix_context_artifacts_sha256 (sha256),
  KEY ix_context_artifacts_created_at (created_at),
  KEY idx_context_artifacts_thread_created (thread_id, created_at),
  KEY idx_context_artifacts_run_unit (run_id, unit_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='智能体上下文大结果工件元数据表';
