CREATE TABLE IF NOT EXISTS learning_plans (
  plan_id VARCHAR(36) NOT NULL,
  user_id VARCHAR(36) NOT NULL,
  template_id VARCHAR(100) NULL,
  title VARCHAR(255) NOT NULL,
  summary TEXT NULL,
  domain VARCHAR(50) NOT NULL DEFAULT 'ne',
  goal TEXT NULL,
  baseline VARCHAR(50) NULL,
  depth VARCHAR(50) NULL,
  duration_days INT NOT NULL DEFAULT 7,
  daily_minutes INT NOT NULL DEFAULT 90,
  kb_ids JSON NULL,
  style_snapshot JSON NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  progress INT NOT NULL DEFAULT 0,
  mastery INT NOT NULL DEFAULT 0,
  accent VARCHAR(20) NULL,
  surface VARCHAR(20) NULL,
  course_type VARCHAR(100) NULL,
  current_node_id VARCHAR(36) NULL,
  metadata JSON NULL,
  started_at DATETIME NULL,
  completed_at DATETIME NULL,
  archived_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (plan_id),
  KEY ix_learning_plans_user_id (user_id),
  KEY ix_learning_plans_template_id (template_id),
  KEY ix_learning_plans_status (status),
  KEY ix_learning_plans_current_node_id (current_node_id),
  KEY ix_learning_plans_created_at (created_at),
  KEY idx_learning_plan_user_status (user_id, status, updated_at),
  CONSTRAINT fk_learning_plan_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='自定义学习计划表';

CREATE TABLE IF NOT EXISTS learning_plan_nodes (
  node_id VARCHAR(36) NOT NULL,
  plan_id VARCHAR(36) NOT NULL,
  parent_node_id VARCHAR(36) NULL,
  order_index INT NOT NULL DEFAULT 0,
  title VARCHAR(255) NOT NULL,
  subtitle VARCHAR(255) NULL,
  objective TEXT NULL,
  explanation TEXT NULL,
  quiz_questions JSON NULL,
  prerequisites JSON NULL,
  resources JSON NULL,
  tasks JSON NULL,
  checks JSON NULL,
  resource TEXT NULL,
  task TEXT NULL,
  `check` TEXT NULL,
  day VARCHAR(50) NULL,
  node_type VARCHAR(20) NOT NULL DEFAULT 'concept',
  difficulty VARCHAR(20) NULL,
  estimated_minutes INT NOT NULL DEFAULT 60,
  unlock_rule JSON NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'locked',
  mastery INT NOT NULL DEFAULT 0,
  study_signals JSON NULL,
  explore_cache JSON NULL,
  due_at DATETIME NULL,
  completed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (node_id),
  KEY ix_learning_plan_nodes_plan_id (plan_id),
  KEY ix_learning_plan_nodes_status (status),
  KEY idx_learning_node_plan_order (plan_id, order_index),
  KEY idx_learning_node_plan_status (plan_id, status),
  CONSTRAINT fk_learning_node_plan FOREIGN KEY (plan_id) REFERENCES learning_plans(plan_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='自定义学习计划节点表';

CREATE TABLE IF NOT EXISTS learning_node_attempts (
  attempt_id VARCHAR(36) NOT NULL,
  plan_id VARCHAR(36) NOT NULL,
  node_id VARCHAR(36) NOT NULL,
  user_id VARCHAR(36) NOT NULL,
  action_type VARCHAR(20) NOT NULL,
  payload JSON NULL,
  score INT NULL,
  diagnosis JSON NULL,
  duration_seconds INT NULL,
  mastery_before INT NULL,
  mastery_after INT NULL,
  source VARCHAR(30) NOT NULL DEFAULT 'manual',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (attempt_id),
  KEY ix_learning_node_attempts_plan_id (plan_id),
  KEY ix_learning_node_attempts_node_id (node_id),
  KEY ix_learning_node_attempts_user_id (user_id),
  KEY ix_learning_node_attempts_created_at (created_at),
  KEY idx_learning_attempt_node_user_created (node_id, user_id, created_at),
  CONSTRAINT fk_learning_attempt_plan FOREIGN KEY (plan_id) REFERENCES learning_plans(plan_id) ON DELETE CASCADE,
  CONSTRAINT fk_learning_attempt_node FOREIGN KEY (node_id) REFERENCES learning_plan_nodes(node_id) ON DELETE CASCADE,
  CONSTRAINT fk_learning_attempt_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='自定义学习节点学习记录表';

CREATE TABLE IF NOT EXISTS learning_plan_adjustments (
  adjustment_id VARCHAR(36) NOT NULL,
  plan_id VARCHAR(36) NOT NULL,
  trigger_type VARCHAR(50) NOT NULL,
  before_snapshot JSON NULL,
  after_snapshot JSON NULL,
  reason TEXT NULL,
  accepted TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (adjustment_id),
  KEY ix_learning_plan_adjustments_plan_id (plan_id),
  KEY ix_learning_plan_adjustments_created_at (created_at),
  KEY idx_learning_adjustment_plan_created (plan_id, created_at),
  CONSTRAINT fk_learning_adjustment_plan FOREIGN KEY (plan_id) REFERENCES learning_plans(plan_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='自定义学习计划调整记录表';
